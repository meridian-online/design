# Everything the pages reach for. Directories are copied whole; the check below
# is what proves the list is sufficient, so this stays a starting point rather
# than a promise.
ASSETS: list[str] = [
    "meridian-design/brand/motion",  # the four tracked artefacts, both formats
    "motion/preview/lottie.min.js",  # vendored so the pages work offline
    "motion/output",  # regenerated by `build_form.py --explore`
    "motion/README.md",  # linked from the preview pages
]

# References a static site cannot resolve for us. `schemes.html` builds its
# filenames in a template literal, so the check below reads the page's own
# scheme list and asks for the files that list implies.
DYNAMIC = "motion/preview/schemes.html"


def tokens_css() -> str:
    """The emitted token block, with its dark half taught to follow the reader.

    `tokens.css` puts dark under a `.dark` class because that is what the web
    app toggles. A static page has nothing to toggle it, so the same block is
    repeated under `prefers-color-scheme` — repeated by reading it, not by
    restating it, which is the rule every other artefact here follows.
    """
    css = (ROOT / "meridian-design/tests/snapshots/tokens.css").read_text()
    _, _, dark = css.partition("\n.dark {")
    dark = dark.rstrip().removesuffix("}")
    return f"{css}\n@media (prefers-color-scheme: dark) {{\n  :root {{{dark}}}\n}}\n"


