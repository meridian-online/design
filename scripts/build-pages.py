def local_refs(page: str) -> set[str]:
    """Every same-origin path a page asks for, as written."""
    refs: set[str] = set()
    refs |= set(re.findall(r"""(?:src|href)=["']([^"'>]+)""", page))
    refs |= set(re.findall(r"""url\(["']?([^)"']+)""", page))
    refs |= set(re.findall(r"""["'](\.\.?/[^"'`]+)["']""", page))
    return {
        r.split("#")[0].split("?")[0]
        for r in refs
        if not r.startswith(("http://", "https://", "//", "#", "data:", "mailto:"))
    }


def scheme_files(page: str) -> set[str]:
    """The scratch files `schemes.html`'s own scheme list implies.

    Its filenames are built in a template literal, so they cannot be read off
    the source the way a plain `src` can. Reading the list it iterates is the
    next best thing, and it is the half that actually drifts — the generator's
    scheme names and the page's have to agree.
    """
    block = re.search(r"const SCHEMES = \[(.*?)\];", page, re.S)
    if not block:
        return set()
    names = re.findall(r"""\[\s*['"]([^'"]+)['"]""", block.group(1))
    return {
        f"motion/output/form-{n}{suffix}.json" for n in names for suffix in ("", "-dark")
    }


def main() -> int:
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "_site")
    if out.exists():
        shutil.rmtree(out)

    published = []
    for path, title, blurb in PAGES:
        source = ROOT / path
        if not source.is_file():
            sys.exit(f"build-pages: {path} is listed but not in the tree")
        published.append((path, title, blurb))
        (out / path).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, out / path)

    for asset in ASSETS:
        source = ROOT / asset
        target = out / asset
        if source.is_dir():
            shutil.copytree(source, target, dirs_exist_ok=True)
        elif source.is_file():
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
        else:
            sys.exit(
                f"build-pages: {asset} is missing. If it is motion/output/, the "
                f"exploration scratch has not been built — run "
                f"`cd motion && python3 build_form.py --explore` first."
            )

    (out / "index.html").write_text(index(published))

    # Nothing is published until every reference in it resolves.
    broken: list[str] = []
    for path, _, _ in published + [("index.html", "", "")]:
        page = (out / path).read_text(encoding="utf-8", errors="replace")
        wanted = local_refs(page)
        if path == DYNAMIC:
            wanted |= {f"/{f}" for f in scheme_files(page)}
        for ref in sorted(wanted):
            here = (out / path).parent
            target = (out / ref.lstrip("/")) if ref.startswith("/") else (here / ref)
            if not target.resolve().exists():
                broken.append(f"  {path}  ->  {ref}")

    if broken:
        print("build-pages: references that would 404 once published:\n")
        print("\n".join(broken))
        return 1

    files = sum(1 for p in out.rglob("*") if p.is_file())
    size = sum(p.stat().st_size for p in out.rglob("*") if p.is_file())
    print(
        f"build-pages: {len(published)} pages, {files} files, "
        f"{size / 1024 / 1024:.1f} MB — every reference resolves."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
