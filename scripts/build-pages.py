#!/usr/bin/env python3
"""Assemble the published evidence site, and refuse to publish a broken one.

The repo already holds the pages that show its work — the palette review
gallery, and the preview and measurement harnesses the brand motion was built
against. Until now they were invisible without cloning and serving from the
repository root, which is a strange place to keep the evidence for decisions
the ADRs cite.

Three things this script does, in one place on purpose:

1. **Copies.** The site mirrors the repository layout rather than flattening
   it, because every preview page addresses its assets with paths like
   `../../meridian-design/brand/motion/form.svg`. Flattening would mean
   rewriting the pages for publication, and a page that is rewritten on the way
   out is no longer the page anyone tested.

2. **Writes the index from the same manifest it copies from.** One list, so the
   landing page cannot advertise something that was not published, nor omit
   something that was.

3. **Checks every reference resolves inside the built site**, and exits
   non-zero if one does not. A dangling `src` is invisible to every other gate
   here: the file is tracked, the HTML is valid, CI is green, and the page is
   quietly broken for everyone but the person who has the repo checked out.

Run it locally the same way CI does:

    python3 scripts/build-pages.py _site && python3 -m http.server -d _site
"""

from __future__ import annotations

import html
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The published pages, in the order the index lists them. The third field is
